// MF-12: pairing overlay on the frame.
// Shown when no phone is paired, or on demand after a >= 3 s still long-press.
// Talks only to localhost-only routes (/pairing/state, /pairing/start, /pairing/sign-out-all).
(function(){
    const PAIR_HOLD = 3000;
    const POLL = 2000;
    const MOVE_TOLERANCE = 20;

    const overlay = document.getElementById("pairOverlay");
    const codeEl = document.getElementById("pairCode");
    const qrEl = document.getElementById("pairQr");
    const ssidEl = document.getElementById("pairSsid");
    const urlEl = document.getElementById("pairUrl");
    const closeBtn = document.getElementById("pairClose");
    const signOutBtn = document.getElementById("pairSignOut");

    let onDemand = false;
    let paired = 0;
    let starting = false;
    let holdTimer = null;
    let sx = 0, sy = 0;

    async function getState(){
        const r = await fetch("/pairing/state", {cache: "no-store"});
        if(!r.ok){ throw new Error("state " + r.status); }
        return r.json();
    }

    async function startRound(){
        if(starting){ return null; }
        starting = true;
        try{
            const r = await fetch("/pairing/start", {method: "POST"});
            return r.ok ? r.json() : null;
        }finally{
            starting = false;
        }
    }

    function render(st){
        paired = st.paired;
        ssidEl.textContent = st.ssid ? "Wi-Fi: " + st.ssid : "";
        urlEl.textContent = st.url;
        if(st.round){
            codeEl.textContent = st.round.code.slice(0, 3) + " " + st.round.code.slice(3);
            qrEl.innerHTML = st.round.qr_svg;     // generated by our own server (segno)
        }
        closeBtn.hidden = paired === 0;
        signOutBtn.hidden = paired === 0;
    }

    async function tick(){
        try{
            let st = await getState();
            const visible = st.paired === 0 || onDemand;
            if(visible && !st.round){
                st = (await startRound()) || st;      // first round, expired or used
            }
            if(onDemand && st.paired > paired){
                onDemand = false;                    // the new phone just paired
            }
            render(st);
            overlay.classList.toggle("visible", st.paired === 0 || onDemand);
        }catch(e){
            console.warn("pairing state unavailable", e);
        }
    }

    function show(){
        onDemand = true;
        tick();
    }

    closeBtn.addEventListener("click", (e)=>{ e.stopPropagation(); onDemand = false; tick(); });
    signOutBtn.addEventListener("click", async (e)=>{
        e.stopPropagation();
        await fetch("/pairing/sign-out-all", {method: "POST"});
        tick();
    });

    document.addEventListener("pointerdown", (e)=>{
        sx = e.clientX; sy = e.clientY;
        clearTimeout(holdTimer);
        holdTimer = setTimeout(show, PAIR_HOLD);
    });
    document.addEventListener("pointermove", (e)=>{
        if(Math.abs(e.clientX - sx) > MOVE_TOLERANCE || Math.abs(e.clientY - sy) > MOVE_TOLERANCE){
            clearTimeout(holdTimer);
        }
    });
    document.addEventListener("pointerup", ()=> clearTimeout(holdTimer));
    document.addEventListener("pointercancel", ()=> clearTimeout(holdTimer));

    window.memoryFramePairing = {show: show, tick: tick};
    tick();
    setInterval(tick, POLL);
})();
